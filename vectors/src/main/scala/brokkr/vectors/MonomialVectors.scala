package brokkr.vectors

import java.io.PrintWriter
import scala.util.Random
import scotty.quantum.Circuit
import scotty.quantum.gate.StandardGate.{CCNOT, CNOT, ISWAP, SWAP, X, Y}
import scotty.simulator.fusion.{BlockForm, FusedKernel, GateFusion, MonomialOperator}

/** Emits reference vectors for the Chisel `MonomialKernel`, from Scotty.
  *
  * The block is fused from gates that include a Toffoli, so the permutation it contains is not
  * affine and an Omega network could not route it — which is the point of the Benes network the
  * kernel uses. The control bits are computed here, by [[BenesRouter]], exactly as the host would
  * compute them once per block.
  */
object MonomialVectors:
  val Width: Int = 3

  def main(args: Array[String]): Unit =
    val path = args.headOption.getOrElse("rtl/src/test/resources/monomial-vectors.txt")
    val circuit = Circuit(
      Circuit.generateRegister(Width),
      X(0), CNOT(0, 1), CCNOT(0, 1, 2), SWAP(0, 2), Y(1), ISWAP(1, 2)
    )
    val fused = GateFusion.fuse(circuit, Width)
    val block = fused.blocks
      .find(_.form == BlockForm.Monomial)
      .getOrElse(sys.error("expected the pass to produce a monomial block"))
    val monomial = block.operator.asInstanceOf[MonomialOperator]

    require(block.width == Width, s"expected a width-$Width block, got ${block.width}")

    val shape = PermutationStudy.classify(monomial.rows, Width)
    val control = BenesRouter.route(monomial.rows)
    val amplitudes = 1 << Width
    val random = new Random(20261018L)
    val state = Array.tabulate(2 * amplitudes)(_ => (random.nextDouble() - 0.5) * 1.2)
    val golden = state.clone()

    FusedKernel.applyBlock(golden, Width, block)

    // The control bits as one integer, bit i being switch i, which is how the kernel takes them.
    val packed = control.zipWithIndex.foldLeft(BigInt(0)):
      case (acc, (set, bit)) => if set then acc.setBit(bit) else acc

    val out = new PrintWriter(path)

    out.println("# generated by brokkr.vectors.MonomialVectors from Scotty's FusedKernel.applyBlock")
    out.println(s"# width=$Width, permutation shape=$shape")
    out.println(s"width $Width")
    out.println(s"permutation ${monomial.rows.mkString(",")}")
    out.println(s"control $packed")
    out.println(s"phases ${monomial.values.mkString(",")}")
    out.println("# lane inRe inIm outRe outIm")

    (0 until amplitudes).foreach: i =>
      out.println(s"$i ${state(2 * i)} ${state(2 * i + 1)} ${golden(2 * i)} ${golden(2 * i + 1)}")

    out.close()

    println(s"permutation ${monomial.rows.mkString(",")} is $shape")
    println(s"${control.length} Benes control bits, packed as $packed")
    println(s"wrote $amplitudes lanes to $path")
