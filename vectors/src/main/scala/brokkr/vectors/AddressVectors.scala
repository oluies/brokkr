package brokkr.vectors

import java.io.PrintWriter
import scotty.simulator.fusion.FusedKernel

/** Emits exhaustive reference vectors for the Chisel `AddressGen`, straight from Scotty.
  *
  * Scotty is the golden model, and it is Scala 3; the testbench is Scala 2.13 because Chisel is.
  * The two cannot call each other — `-Ytasty-reader` fails on Scotty's 3.9 TASTy — so the vectors
  * cross the gap as a file, which is what a C++ difftest harness or an FPGA bring-up would use in
  * any case.
  *
  * Regenerate with:
  * {{{
  * ./mill vectors.runMain brokkr.vectors.AddressVectors rtl/src/test/resources/address-vectors.txt
  * }}}
  */
object AddressVectors:
  val QubitCount: Int = 6
  val MaxWidth: Int = 3

  def main(args: Array[String]): Unit =
    val path = args.headOption.getOrElse("rtl/src/test/resources/address-vectors.txt")
    val out = new PrintWriter(path)

    out.println(s"# generated by brokkr.vectors.AddressVectors from Scotty's FusedKernel.baseOf")
    out.println(s"# qubitCount=$QubitCount maxWidth=$MaxWidth")
    out.println(s"# slice qubits base")

    var count = 0

    for
      width <- 1 to MaxWidth
      qubits <- (0 until QubitCount).toList.combinations(width)
      slice <- 0 until (1 << (QubitCount - width))
    do
      out.println(s"$slice ${qubits.mkString(",")} ${FusedKernel.baseOf(slice, qubits.toArray)}")
      count += 1

    out.close()
    println(s"wrote $count vectors to $path")
