package brokkr.vectors

import java.io.PrintWriter
import scala.util.Random
import scotty.quantum.Circuit
import scotty.quantum.gate.StandardGate.{CPHASE, RZ, T}
import scotty.simulator.fusion.{BlockForm, DiagonalOperator, FusedKernel, GateFusion}

/** Emits reference vectors for the Chisel `DiagonalKernel`, from Scotty.
  *
  * The diagonal path is the cheapest of the three datapaths and the one a dense-only engine throws
  * away: every amplitude is scaled in place by one of `2^k` phases, with no gather, no scatter and
  * no shuffle network. Here that is a phase table, one complex multiplier and a stream.
  *
  * The block is a real fused operator rather than a hand-written table — `RZ`, `CPHASE` and `T`
  * fused over the support {0, 2} — so the vectors exercise the pass as well as the kernel.
  */
object DiagonalVectors:
  val QubitCount: Int = 4
  val MaxWidth: Int = 2

  def main(args: Array[String]): Unit =
    val path = args.headOption.getOrElse("rtl/src/test/resources/diagonal-vectors.txt")
    val circuit = Circuit(Circuit.generateRegister(QubitCount), RZ(0.7, 0), CPHASE(1.1, 0, 2), T(2))
    val fused = GateFusion.fuse(circuit, MaxWidth)
    val block = fused.blocks
      .find(_.form == BlockForm.Diagonal)
      .getOrElse(sys.error("expected the pass to produce a diagonal block"))
    val diagonal = block.operator.asInstanceOf[DiagonalOperator]

    // A deterministic input state. It is not normalised, which does not matter: the kernel scales
    // each amplitude independently, so any amplitude in range is a valid test.
    val random = new Random(20261017L)
    val amplitudes = 1 << QubitCount
    val state = Array.tabulate(2 * amplitudes)(_ => (random.nextDouble() - 0.5) * 1.4)
    val golden = state.clone()

    FusedKernel.applyDiagonal(golden, diagonal.values, block.qubits.toArray, 0, amplitudes)

    val out = new PrintWriter(path)

    out.println("# generated by brokkr.vectors.DiagonalVectors from Scotty's FusedKernel.applyDiagonal")
    out.println(s"# qubitCount=$QubitCount maxWidth=$MaxWidth")
    out.println(s"qubits ${block.qubits.mkString(",")}")
    out.println(s"width ${block.width}")
    out.println(s"table ${diagonal.values.mkString(",")}")
    out.println("# index inRe inIm outRe outIm")

    (0 until amplitudes).foreach: i =>
      out.println(s"$i ${state(2 * i)} ${state(2 * i + 1)} ${golden(2 * i)} ${golden(2 * i + 1)}")

    out.close()
    println(s"wrote $amplitudes vectors over support ${block.qubits.mkString(",")} to $path")
