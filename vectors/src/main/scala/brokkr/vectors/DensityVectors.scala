package brokkr.vectors

import java.io.PrintWriter
import scala.util.Random
import scotty.quantum.density.ComplexMatrix
import scotty.quantum.math.Complex

/** Reference vectors for the Chisel `ComplexGemm`, from Scotty's own complex matrix product.
  *
  * The density-matrix engine's whole kernel is `C = A · B` over complex entries: a channel is
  * `rho -> sum K rho K†`, which is two of these per Kraus operator. So verifying the product
  * verifies the engine, and Scotty's `ComplexMatrix.multiply` is the golden model for it exactly as
  * `FusedKernel` was for the state-vector path.
  *
  * `A` is `tile x depth` and `B` is `depth x tile`, which is the shape an outer-product array
  * consumes: one column of `A` and one row of `B` per cycle, accumulating into a `tile x tile`
  * result.
  */
object DensityVectors:
  val Tile: Int = 4

  /** Several depths, because the claim worth testing is that error does not grow with depth — the
    * accumulator is widened and narrowed only on the way out, which is what licenses running this
    * to the depth `2^n` a ten-qubit channel needs.
    */
  val Depths: Seq[Int] = Seq(4, 8, 16, 32)

  def main(args: Array[String]): Unit =
    val path = args.headOption.getOrElse("rtl/src/test/resources/gemm-vectors.txt")
    val random = Random(20261018L)
    val out = new PrintWriter(path)

    out.println("# generated by brokkr.vectors.DensityVectors from Scotty's ComplexMatrix.multiply")
    out.println(s"tile $Tile")
    out.println(s"depths ${Depths.mkString(",")}")

    Depths.foreach: depth =>
      // Scaled by the depth so the accumulated product stays inside the fixed-point range whatever
      // the depth is; otherwise a deep case would overflow for a reason unrelated to rounding.
      def entry(): Complex =
        val scale = 2.0 * math.sqrt(depth.toDouble)

        Complex((random.nextDouble() - 0.5) / scale, (random.nextDouble() - 0.5) / scale)

      val a = ComplexMatrix(Tile, depth, Vector.tabulate(Tile * depth)(_ => entry()))
      val b = ComplexMatrix(depth, Tile, Vector.tabulate(depth * Tile)(_ => entry()))
      val c = a.multiply(b)

      (0 until depth).foreach: step =>
        val column = (0 until Tile).flatMap(row => Seq(a.realAt(row, step), a.imagAt(row, step)))
        val row = (0 until Tile).flatMap(col => Seq(b.realAt(step, col), b.imagAt(step, col)))

        out.println(s"step $depth $step ${column.mkString(",")} ${row.mkString(",")}")

      (0 until Tile).foreach: row =>
        (0 until Tile).foreach: col =>
          out.println(s"result $depth $row $col ${c.realAt(row, col)} ${c.imagAt(row, col)}")

    out.close()
    println(s"wrote ${Tile}x$Tile products at depths ${Depths.mkString(", ")} to $path")
