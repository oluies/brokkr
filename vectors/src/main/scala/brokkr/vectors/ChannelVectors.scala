package brokkr.vectors

import java.io.PrintWriter
import scala.util.Random
import scotty.quantum.density.{Channel, ComplexMatrix, DensityMatrix}
import scotty.quantum.math.Complex

/** Reference vectors for the Chisel `ChannelEngine`: a whole Kraus channel, end to end.
  *
  * `rho -> sum K rho K†` is the density-matrix engine's actual job, not a kernel inside it. This
  * emits a real channel from Scotty — a depolarizing channel on one qubit of a two-qubit system,
  * four Kraus operators of four by four — together with the state it acts on and the answer, so
  * the hardware can be checked against the simulator rather than against a matrix product.
  */
object ChannelVectors:
  val Qubits: Int = 2
  val Dimension: Int = 1 << Qubits

  def main(args: Array[String]): Unit =
    val path = args.headOption.getOrElse("rtl/src/test/resources/channel-vectors.txt")
    val random = Random(20261018L)
    val channel = Channel.depolarizing(0.3).tensor(Channel.identity(2))

    require(channel.inputDim == Dimension, s"expected a ${Dimension}-dimensional channel")

    // A valid state: Hermitian, positive semidefinite, unit trace. Scaled down so that every
    // intermediate of K rho K† stays inside the fixed-point range.
    val seed = ComplexMatrix(
      Dimension,
      Dimension,
      Vector.tabulate(Dimension * Dimension)(_ => Complex(random.nextDouble() - 0.5, random.nextDouble() - 0.5))
    )
    val rho = DensityMatrix(Vector.fill(Qubits)(2), ComplexMatrix.outer(seed, seed)).normalized
    val result = channel(rho)

    require(rho.isHermitian(), "rho should be Hermitian")
    require(math.abs(rho.realTrace - 1.0) < 1e-9, "rho should have unit trace")

    val out = new PrintWriter(path)

    def emit(label: String, index: Int, matrix: ComplexMatrix): Unit =
      (0 until Dimension).foreach: row =>
        val entries = (0 until Dimension)
          .flatMap(col => Seq(matrix.realAt(row, col), matrix.imagAt(row, col)))

        out.println(s"$label $index $row ${entries.mkString(",")}")

    out.println("# generated by brokkr.vectors.ChannelVectors from Scotty's Channel.apply")
    out.println(s"dimension $Dimension")
    out.println(s"kraus ${channel.kraus.length}")

    emit("rho", 0, rho.matrix)
    channel.kraus.zipWithIndex.foreach((k, i) => emit("k", i, k))
    emit("result", 0, result.matrix)

    out.close()

    println(s"wrote a ${Dimension}x$Dimension state, ${channel.kraus.length} Kraus operators")
    println(f"  trace of rho ${rho.realTrace}%.6f, trace of the result ${result.realTrace}%.6f")
