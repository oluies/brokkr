package brokkr.vectors

import java.io.PrintWriter
import scala.util.Random
import scotty.quantum.density.{Channel, ComplexMatrix, DensityMatrix}
import scotty.quantum.math.Complex

/** Reference vectors for `ChannelEngine`: several channels, several states, each with its answer.
  *
  * The engine was first checked against one channel on one state, which is thin for the thing the
  * whole assessment rests on — the state-vector path it is being compared against is checked
  * against randomised circuits across the entire gate set. This closes that gap: every square
  * channel Scotty offers, each applied to several random states.
  *
  * Erasure is absent, and not by oversight. It maps dimension 2 to dimension 3, and the engine
  * assumes `rho`, `K` and the result are all the same square size. That is a capability gap on a
  * channel `pctc` actually uses, recorded here rather than hidden by only testing what fits.
  */
object ChannelVectors:
  val Qubits: Int = 2
  val Dimension: Int = 1 << Qubits
  val StatesPerChannel: Int = 3

  /** Square channels on one qubit, lifted to the two-qubit register. */
  def channels: Seq[(String, Channel)] = Seq(
    "depolarizing" -> Channel.depolarizing(0.3),
    "amplitudeDamping" -> Channel.amplitudeDamping(0.4),
    "dephasing" -> Channel.dephasing(0.25)
  ).map((name, channel) => name -> channel.tensor(Channel.identity(2)))

  /** A valid state: Hermitian, positive semidefinite, unit trace. */
  def randomState(random: Random): DensityMatrix =
    val seed = ComplexMatrix(
      Dimension,
      Dimension,
      Vector.tabulate(Dimension * Dimension)(_ =>
        Complex(random.nextDouble() - 0.5, random.nextDouble() - 0.5)
      )
    )

    DensityMatrix(Vector.fill(Qubits)(2), ComplexMatrix.outer(seed, seed)).normalized

  def main(args: Array[String]): Unit =
    val path = args.headOption.getOrElse("rtl/src/test/resources/channel-vectors.txt")
    val random = Random(20261018L)
    val out = new PrintWriter(path)

    def emit(label: String, caseIndex: Int, operator: Int, matrix: ComplexMatrix): Unit =
      (0 until Dimension).foreach: row =>
        val entries = (0 until Dimension)
          .flatMap(col => Seq(matrix.realAt(row, col), matrix.imagAt(row, col)))

        out.println(s"$label $caseIndex $operator $row ${entries.mkString(",")}")

    out.println("# generated by brokkr.vectors.ChannelVectors from Scotty's Channel.apply")
    out.println(s"dimension $Dimension")
    out.println(s"cases ${channels.length * StatesPerChannel}")

    var caseIndex = 0

    channels.foreach: (name, channel) =>
      require(channel.inputDim == Dimension && channel.outputDim == Dimension, s"$name is not square")

      (0 until StatesPerChannel).foreach: _ =>
        val rho = randomState(random)
        val result = channel(rho)

        require(rho.isHermitian(), s"$name: rho should be Hermitian")
        require(math.abs(rho.realTrace - 1.0) < 1e-9, s"$name: rho should have unit trace")

        out.println(s"case $caseIndex $name ${channel.kraus.length}")
        emit("rho", caseIndex, 0, rho.matrix)
        channel.kraus.zipWithIndex.foreach((k, i) => emit("k", caseIndex, i, k))
        emit("result", caseIndex, 0, result.matrix)

        caseIndex += 1

    out.close()

    println(s"wrote $caseIndex cases over ${channels.length} channels")
    channels.foreach((name, channel) => println(s"  $name: ${channel.kraus.length} Kraus operators"))
