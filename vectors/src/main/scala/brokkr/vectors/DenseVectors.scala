package brokkr.vectors

import java.io.PrintWriter
import scala.util.Random
import scotty.quantum.Circuit
import scotty.quantum.gate.StandardGate.{CNOT, H, RX, RY}
import scotty.simulator.fusion.{BlockForm, DenseOperator, FusedKernel, GateFusion}

/** Emits reference vectors for the Chisel `DenseKernel`, from Scotty.
  *
  * The register is exactly as wide as the block, so the state is a single slice and the golden
  * output is the bare matrix-vector product — which is what the kernel computes, without the
  * address arithmetic that would surround it in the full engine.
  *
  * The input state is normalised so that a unitary operator keeps every output amplitude inside the
  * fixed-point range, which is the condition the kernel is designed for rather than a convenience.
  */
object DenseVectors:
  val Width: Int = 3

  def main(args: Array[String]): Unit =
    val path = args.headOption.getOrElse("rtl/src/test/resources/dense-vectors.txt")
    val circuit = Circuit(
      Circuit.generateRegister(Width),
      H(0), RX(0.9, 1), RY(1.3, 2), CNOT(0, 1), H(2), RX(0.4, 0)
    )
    val fused = GateFusion.fuse(circuit, Width)
    val block = fused.blocks
      .find(_.form == BlockForm.Dense)
      .getOrElse(sys.error("expected the pass to produce a dense block"))
    val dense = block.operator.asInstanceOf[DenseOperator]

    require(block.width == Width, s"expected a width-$Width block, got ${block.width}")

    val random = new Random(20261018L)
    val amplitudes = 1 << Width
    val state = Array.tabulate(2 * amplitudes)(_ => random.nextDouble() - 0.5)
    val norm = Math.sqrt(state.map(x => x * x).sum)

    (0 until state.length).foreach(i => state(i) /= norm)

    val golden = state.clone()

    FusedKernel.applyBlock(golden, Width, block)

    val out = new PrintWriter(path)
    val flat =
      for
        row <- 0 until amplitudes
        col <- 0 until amplitudes
        part <- Seq(dense.matrix.realAt(row, col), dense.matrix.imagAt(row, col))
      yield part

    out.println("# generated by brokkr.vectors.DenseVectors from Scotty's FusedKernel.applyBlock")
    out.println(s"# width=$Width, operator is row-major (re,im) pairs")
    out.println(s"width $Width")
    out.println(s"operator ${flat.mkString(",")}")
    out.println("# index inRe inIm outRe outIm")

    (0 until amplitudes).foreach: i =>
      out.println(s"$i ${state(2 * i)} ${state(2 * i + 1)} ${golden(2 * i)} ${golden(2 * i + 1)}")

    out.close()

    // The same vectors as hex, for the SystemVerilog testbench to $readmemh. Expected outputs are
    // computed with the kernel's own fixed-point arithmetic rather than rounded from the doubles
    // above, so the Verilator run can compare bit for bit instead of within a tolerance.
    val directory = java.io.File(path).getAbsoluteFile.getParent

    writeHex(s"$directory/dense-operator.hex", flat.map(fixed))
    writeHex(
      s"$directory/dense-input.hex",
      (0 until amplitudes).flatMap(i => Seq(fixed(state(2 * i)), fixed(state(2 * i + 1))))
    )
    writeHex(s"$directory/dense-expected.hex", expectedFixed(flat.map(fixed).toVector, state, amplitudes))

    println(s"wrote a ${amplitudes}x$amplitudes dense operator and $amplitudes amplitudes to $path")
    println(s"wrote dense-operator.hex, dense-input.hex and dense-expected.hex beside it")

  val FractionBits: Int = 23

  def fixed(value: Double): BigInt =
    BigDecimal(value).*(BigDecimal(BigInt(1) << FractionBits)).setScale(0, BigDecimal.RoundingMode.HALF_UP).toBigInt

  /** Two's complement, 24 bits, as six hex digits. */
  def writeHex(path: String, values: Seq[BigInt]): Unit =
    val out = new PrintWriter(path)
    val modulus = BigInt(1) << 24

    values.foreach(v => out.println(((v % modulus) + modulus) % modulus match
      case masked => f"${masked}%06x"
    ))

    out.close()

  /** The kernel's arithmetic, so the testbench can compare exactly. */
  def expectedFixed(operator: Vector[BigInt], state: Array[Double], amplitudes: Int): Seq[BigInt] =
    (0 until amplitudes).flatMap: row =>
      val (re, im) = (0 until amplitudes).foldLeft((BigInt(0), BigInt(0))):
        case ((accRe, accIm), col) =>
          val eRe = operator(2 * (row * amplitudes + col))
          val eIm = operator(2 * (row * amplitudes + col) + 1)
          val aRe = fixed(state(2 * col))
          val aIm = fixed(state(2 * col + 1))

          (accRe + eRe * aRe - eIm * aIm, accIm + eRe * aIm + eIm * aRe)

      Seq(re >> FractionBits, im >> FractionBits)
