package brokkr

import chisel3._
import chisel3.util._

/** Computes the base amplitude index of a slice, for a block over an ascending qubit support.
  *
  * This is the first piece of the engine, and it is deliberately the smallest one that matters.
  * Applying a fused block means visiting every slice of the state vector: the `2^(n-k)` ways of
  * choosing the bits the block does not touch. The base address of slice `s` is `s` with a zero bit
  * inserted at each supported qubit position, and the block's `2^k` amplitudes then sit at fixed
  * offsets from it.
  *
  * Bit insertion at position `q` is
  * {{{
  * index = (index & ((1 << q) - 1)) | ((index & ~((1 << q) - 1)) << 1)
  * }}}
  * which is one stage here, applied once per supported qubit in ascending order — ascending is what
  * makes it correct, since each insertion shifts the positions above it up by one and the next
  * qubit's position is already expressed in the shifted numbering.
  *
  * It is combinational: `maxWidth` stages, each a mask, a shift and an or. That is cheap, and it is
  * the reason this block is interesting rather than despite it — the whole address path is bit
  * manipulation, which is also why an Omega network is the right fabric for the data path that
  * follows.
  *
  * Verified exhaustively against `scotty.simulator.fusion.FusedKernel.baseOf`, the golden model, via
  * vectors generated by `brokkr.vectors.AddressVectors`.
  *
  * @param qubitCount how many qubits the register has, and so how wide an amplitude index is
  * @param maxWidth   the widest block support this generator serves
  */
class AddressGen(val qubitCount: Int, val maxWidth: Int) extends Module {
  require(qubitCount >= 1, "a register needs at least one qubit")
  require(maxWidth >= 1 && maxWidth <= qubitCount, "block width has to fit in the register")

  /** Bits needed to name a qubit. */
  val indexWidth: Int = math.max(1, log2Ceil(qubitCount))

  /** Bits needed to count the live entries of the support. */
  val countWidth: Int = log2Ceil(maxWidth + 1)

  val io = IO(new Bundle {
    /** The slice to compute a base address for. */
    val slice = Input(UInt(qubitCount.W))

    /** The block's support, ascending. Entries at or past `width` are ignored. */
    val qubits = Input(Vec(maxWidth, UInt(indexWidth.W)))

    /** How many of `qubits` are live. */
    val blockWidth = Input(UInt(countWidth.W))

    val base = Output(UInt(qubitCount.W))
  })

  val stages = Wire(Vec(maxWidth + 1, UInt(qubitCount.W)))

  stages(0) := io.slice

  for (stage <- 0 until maxWidth) {
    val qubit = io.qubits(stage)
    // Low bits of the current index stay put; everything at or above the qubit's position moves up
    // one, which opens the zero bit the supported qubit will occupy.
    val mask = (((1.U << qubit).asUInt - 1.U))(qubitCount - 1, 0)
    val below = stages(stage) & mask
    val above = ((stages(stage) & (~mask).asUInt) << 1)(qubitCount - 1, 0)

    stages(stage + 1) := Mux(stage.U < io.blockWidth, below | above, stages(stage))
  }

  io.base := stages(maxWidth)
}
